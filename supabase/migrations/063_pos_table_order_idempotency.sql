-- ============================================
-- 063: table-QR orders are idempotent, and the 10 s gap is gone
-- ============================================
-- Two review findings on the public table-QR flow:
--
-- 1. A lost response made the diner's retry either fail (the 10 s gap raised
--    `table_order_too_soon` even though the first request had committed) or,
--    after 10 s, create a second identical ticket that staff cannot tell from a
--    genuine extra round. The client now sends an `idempotency_key`; a retry
--    with the same key returns the order that already landed instead of
--    inserting another. The partial unique index is the authority for
--    concurrent duplicates; the route's pre-read is only a fast path.
--
-- 2. The 10 s per-table gap rejected an ordinary second diner: two people at
--    one table tapping send within ten seconds is normal. The 4 / 5 min cap
--    already bounds abuse, so the gap is removed. (It also had to go for
--    idempotency to work: a BEFORE INSERT trigger that raises before the unique
--    index is checked would turn a legitimate retry into a 429.)
--
-- The rate limit stays per table, serialised by the same advisory lock.

BEGIN;

ALTER TABLE orders ADD COLUMN IF NOT EXISTS idempotency_key TEXT;

COMMENT ON COLUMN orders.idempotency_key IS
  'Client-generated key for anonymous table-QR order submission; a retry with the same key returns the original order.';

-- Global uniqueness is enough: the value is a UUID generated by the page. The
-- route still verifies the stored order belongs to the same table before
-- returning it, so a guessed key cannot read another table's order.
CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_idempotency_key
  ON orders (idempotency_key)
  WHERE idempotency_key IS NOT NULL;

CREATE OR REPLACE FUNCTION enforce_table_order_rate_limit()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  -- Only anonymous table-QR orders are rate limited; staff POS orders and
  -- other channels are not.
  IF NEW.delivery_type <> 'dine_in'
     OR NEW.source <> 'web'
     OR NEW.table_id IS NULL THEN
    RETURN NEW;
  END IF;

  -- Serialise inserts for this table until this transaction commits.
  PERFORM pg_advisory_xact_lock(hashtextextended(NEW.table_id::text, 0));

  IF (
    SELECT count(*)
    FROM orders
    WHERE table_id = NEW.table_id
      AND delivery_type = 'dine_in'
      AND source = 'web'
      AND created_at > clock_timestamp() - interval '5 minutes'
  ) >= 4 THEN
    RAISE EXCEPTION 'table_order_rate_limited' USING ERRCODE = 'P0001';
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION enforce_table_order_rate_limit() IS
  'Serialised per-table rate limit for anonymous table-QR orders (4 / 5 min). Duplicate submits are handled by the idempotency key, not a time gap.';

REVOKE ALL ON FUNCTION enforce_table_order_rate_limit()
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION enforce_table_order_rate_limit() TO service_role;

-- ============================================
-- Atomic table deletion
-- ============================================
-- The admin route used to count orders and then delete, which is a TOCTOU: a
-- counter order can land between the two statements, and the FK is ON DELETE
-- SET NULL, so the delete succeeds and silently orphans that order's table_id.
-- Doing both inside one function removes the window. The FOR UPDATE on the
-- table row also makes an insert that references the table wait (FK checks take
-- a KEY SHARE lock) and fail cleanly once the row is gone.
CREATE OR REPLACE FUNCTION delete_restaurant_table(p_table_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  PERFORM 1 FROM restaurant_tables WHERE id = p_table_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'code', 'not_found');
  END IF;

  IF EXISTS (SELECT 1 FROM orders WHERE table_id = p_table_id) THEN
    RETURN jsonb_build_object('ok', false, 'code', 'has_orders');
  END IF;

  DELETE FROM restaurant_tables WHERE id = p_table_id;
  RETURN jsonb_build_object('ok', true);
END;
$$;

COMMENT ON FUNCTION delete_restaurant_table(UUID) IS
  'Delete a table only when no order references it (atomic history check).';

REVOKE ALL ON FUNCTION delete_restaurant_table(UUID)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION delete_restaurant_table(UUID) TO service_role;

COMMIT;
